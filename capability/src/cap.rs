//! Authenticated logical capabilities. A capability is the LRD-REC-v1 record
//!   {cap_expiry, cap_id, cap_nonce, cap_prev, cap_scope, cap_seq}
//! plus cap_mac = HMAC-SHA256(K_auth, "LRD-CAP-v1\0" || LRD-REC-v1(serialization of those 6 fields)).
//! A transition capability addresses exactly one slot: (cap_seq, cap_prev) = (head.seq+1, head.commit)
//! at issuance ("linear addressing"). Only the authority holds K_auth.
use crate::hmac::{ct_eq, hmac_sha256};
use crate::rec::{is_hex256, parse_nat, Rec};
use crate::sha256::{hex, unhex};

pub const CAP_FIELDS: [&str; 6] = ["cap_expiry", "cap_id", "cap_nonce", "cap_prev", "cap_scope", "cap_seq"];

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Scope {
    Transition,
    Read,
    HistoricalRead,
}

impl Scope {
    pub fn token(self) -> &'static str {
        match self {
            Scope::Transition => "transition",
            Scope::Read => "read",
            Scope::HistoricalRead => "historical_read",
        }
    }
    pub fn parse(s: &str) -> Option<Scope> {
        match s {
            "transition" => Some(Scope::Transition),
            "read" => Some(Scope::Read),
            "historical_read" => Some(Scope::HistoricalRead),
            _ => None,
        }
    }
}

#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Cap {
    pub id: String,    // 32 hex (128-bit random)
    pub scope: Scope,
    pub seq: u64,      // transition: the one seq it authorizes; historical_read: max readable seq
    pub prev: String,  // transition: required prev_commit; others: head commit at issuance
    pub nonce: String, // 64 hex (256-bit, OS CSPRNG, generated by the authority)
    pub expiry: u64,   // unix seconds
    pub mac: String,   // 64 hex
}

impl Cap {
    pub fn body(&self) -> Rec {
        Rec::new()
            .with("cap_expiry", self.expiry.to_string())
            .with("cap_id", self.id.clone())
            .with("cap_nonce", self.nonce.clone())
            .with("cap_prev", self.prev.clone())
            .with("cap_scope", self.scope.token())
            .with("cap_seq", self.seq.to_string())
    }
    pub fn mac_input(&self) -> Vec<u8> {
        let mut m = b"LRD-CAP-v1\0".to_vec();
        m.extend_from_slice(&self.body().serialize());
        m
    }
    pub fn compute_mac(&self, key: &[u8]) -> String {
        hex(&hmac_sha256(key, &self.mac_input()))
    }
    pub fn sign(mut self, key: &[u8]) -> Self {
        self.mac = self.compute_mac(key);
        self
    }
    pub fn mac_ok(&self, key: &[u8]) -> bool {
        match unhex(&self.mac) {
            Some(m) => ct_eq(&m, &hmac_sha256(key, &self.mac_input())),
            None => false,
        }
    }
    pub fn to_rec(&self) -> Rec {
        self.body().with("cap_mac", self.mac.clone())
    }
    /// Parse the cap_* fields from any record (proposal or capability file).
    pub fn from_rec(r: &Rec) -> Result<Cap, &'static str> {
        let g = |k| r.get(k).ok_or("malformed");
        let id = g("cap_id")?.to_string();
        if id.len() != 32 || unhex(&id).is_none() {
            return Err("malformed");
        }
        let nonce = g("cap_nonce")?.to_string();
        let prev = g("cap_prev")?.to_string();
        let mac = g("cap_mac")?.to_string();
        if !is_hex256(&nonce) || !is_hex256(&prev) || !is_hex256(&mac) {
            return Err("malformed");
        }
        Ok(Cap {
            id,
            scope: Scope::parse(g("cap_scope")?).ok_or("malformed")?,
            seq: parse_nat(g("cap_seq")?).ok_or("malformed")?,
            prev,
            nonce,
            expiry: parse_nat(g("cap_expiry")?).ok_or("malformed")?,
            mac,
        })
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    fn cap() -> Cap {
        Cap {
            id: "00112233445566778899aabbccddeeff".into(),
            scope: Scope::Transition,
            seq: 1,
            prev: "ab".repeat(32),
            nonce: "cd".repeat(32),
            expiry: 4_000_000_000,
            mac: String::new(),
        }
        .sign(b"k1")
    }
    #[test]
    fn mac_binds_every_field() {
        let c = cap();
        assert!(c.mac_ok(b"k1"));
        assert!(!c.mac_ok(b"k2"));
        let mut d = c.clone();
        d.seq = 2;
        assert!(!d.mac_ok(b"k1"));
        let mut d = c.clone();
        d.scope = Scope::HistoricalRead;
        assert!(!d.mac_ok(b"k1"));
        let mut d = c.clone();
        d.expiry += 1;
        assert!(!d.mac_ok(b"k1"));
        let mut d = c.clone();
        d.nonce = "ce".repeat(32);
        assert!(!d.mac_ok(b"k1"));
        let mut d = c.clone();
        d.prev = "aa".repeat(32);
        assert!(!d.mac_ok(b"k1"));
        assert_eq!(Cap::from_rec(&c.to_rec()).unwrap(), c);
    }
}
