# Expectation-checked bounded Alloy 6 suite for JWST-LRD (TASKS 004, 006, 010).
# Adapted from /workspace/hcalc/alloy/check.sh (multi-module version). Bounded model checks, not proofs.
#
# expectations.tsv lines: module<TAB>command<TAB>kind<TAB>expect   (0 = UNSAT / no counterexample or
# no instance within scope; 1 = SAT / counterexample or instance found).
# For every module: (a) every command listed by `alloy commands` must appear in expectations.tsv with
# the same `expect N` annotation, and vice versa; (b) each command is run sequentially under
# nice -n 19 and must produce the expected SAT/UNSAT. A command with no SAT/UNSAT result is a FAIL.
# Per-command stdout -> logs/stdout/<module>/<command>.txt (OUTSIDE the -o dir, which Alloy wipes);
# solution files -> logs/solutions/<module>/<command>/. Summary -> logs/alloy-check.txt.
set -uo pipefail
ROOT="$(cd "$(dirname "$0")" && pwd)"
JAR="${ALLOY_JAR:-/workspace/hcalc/alloy/tools/org.alloytools.alloy.dist.jar}"
JAVA="${JAVA:-$HOME/bin/java}"
SOLVER="${ALLOY_SOLVER:-glucose}"   # JNI Glucose bundled in the Alloy 6.2.0 jar; sat4j was too slow for the temporal checks
EXP="$ROOT/expectations.tsv"
LOG="$ROOT/logs/alloy-check.txt"
mkdir -p "$ROOT/logs/stdout" "$ROOT/logs/solutions"
fail=0; ok=0
T0=$(date +%s)
{
  echo "# Dual-licensed: AGPL-3.0-only plus SnapKitty Opaque License. Generated by check.sh."
  echo "=== JWST-LRD Alloy expectation check $(date '+%Y-%m-%dT%H:%M:%S%z') ==="
  echo -n "alloy: "; "$JAVA" -jar "$JAR" version 2>/dev/null | head -n 1
  echo "solver: $SOLVER"
  echo -n "java:  "; "$JAVA" -version 2>&1 | head -n 1
  mapfile -t expected < <(grep -vE '^\s*(#|$)' "$EXP")
  mapfile -t modules < <(printf '%s\n' "${expected[@]}" | cut -f1 | sort -u)
  for mod in "${modules[@]}"; do
    ALS="$ROOT/$mod.als"
    [ -f "$ALS" ] || { echo "FAIL missing $ALS"; fail=$((fail+1)); continue; }
    listing=$("$JAVA" -jar "$JAR" commands "$ALS" 2>&1)
    declared=$(printf '%s\n' "$listing" \
      | sed -nE 's/^\s*[0-9]+\s*\.\s+(Check|Run)\s+([A-Za-z0-9_]+)\s.*expect ([01]).*$/'"$mod"'\t\2\t\L\1\E\t\3/p; t; s/^\s*[0-9]+\s*\.\s+(Check|Run)\s+([A-Za-z0-9_]+)\s.*$/'"$mod"'\t\2\t\L\1\E\tMISSING/p' | sort)
    want=$(printf '%s\n' "${expected[@]}" | awk -F'\t' -v m="$mod" '$1==m' | sort)
    if [ "$declared" != "$want" ]; then
      echo "FAIL $mod: expectations.tsv does not match commands/annotations in $mod.als:"
      diff <(printf '%s\n' "$want") <(printf '%s\n' "$declared") | sed 's/^/  /'
      fail=$((fail+1))
    fi
    if printf '%s\n' "$listing" | grep -q '^Warnings'; then echo "WARN $mod: analyzer warnings present"; fi
    echo "module $mod: $(printf '%s\n' "$want" | grep -c .) commands"
  done
  echo
  for line in "${expected[@]}"; do
    IFS=$'\t' read -r mod name kind want <<<"$line"
    OUTD="$ROOT/logs/solutions/$mod/$name"; STD="$ROOT/logs/stdout/$mod/$name.txt"
    mkdir -p "$ROOT/logs/solutions/$mod" "$ROOT/logs/stdout/$mod"
    start=$(date +%s)
    printf "# Dual-licensed: AGPL-3.0-only plus SnapKitty Opaque License. Lines below this header are\n# verbatim stdout+stderr of: nice -n 19 java -jar alloy exec -f -s %s -o logs/solutions/%s/%s -t text -c %s %s.als\n" "$SOLVER" "$mod" "$name" "$name" "$mod" > "$STD"
    nice -n 19 "$JAVA" -jar "$JAR" exec -f -s "$SOLVER" -o "$OUTD" -t text -c "$name" "$ROOT/$mod.als" >> "$STD" 2>&1
    rc=$?
    res=$(tr '\b' ' ' < "$STD" | grep -E "^ *[0-9]+ *\. +$kind +$name " | grep -oE '\b(UNSAT|SAT)\b' | tail -n 1)
    case "$res" in UNSAT) got=0 ;; SAT) got=1 ;; *) got="none(rc=$rc)" ;; esac
    secs=$(( $(date +%s) - start ))
    if [ "$got" = "$want" ]; then
      printf 'ok   %-22s %-5s %-40s expect %s got %-5s (%ss)\n' "$mod" "$kind" "$name" "$want" "$res" "$secs"; ok=$((ok+1))
    else
      printf 'FAIL %-22s %-5s %-40s expect %s got %-5s (%ss)\n' "$mod" "$kind" "$name" "$want" "${res:-$got}" "$secs"; fail=$((fail+1))
    fi
  done
  echo
  echo "=== summary: ok=$ok fail=$fail total_wall=$(( $(date +%s) - T0 ))s ==="
} 2>&1 | tee "$LOG"
grep -q "=== summary: ok=[0-9]* fail=0 " "$LOG"
