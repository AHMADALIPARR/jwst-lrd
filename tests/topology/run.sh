# tests/topology/run.sh -- simplicial topology ledger test runner (research/CONTRACTS.md).
# Prints one line per test: PASS <name> | FAIL <name> <why> | UNAVAILABLE <name> <reason>.
# Exits nonzero only if some test FAILed.  Everything runs under nice -n 19.
set -u
HERE="$(cd "$(dirname "$0")" && pwd)"
ROOT="$(cd "$HERE/../.." && pwd)"
EVD="$HERE/evidence"
FUTD="$ROOT/futhark/topology"
FIXD="$FUTD/fixtures"
SELFD="$ROOT/self/topology"
GEOD="$SELFD/geometry"
TOOLS="${TOPO_TOOLS:-/workspace/_topology_tools}"
mkdir -p "$EVD" "$FIXD" "$GEOD" "$HERE/build"
NFAIL=0
pass() { echo "PASS $1"; }
fail() { echo "FAIL $1 $2"; NFAIL=$((NFAIL+1)); }
unav() { echo "UNAVAILABLE $1 $2"; }
N="nice -n 19"

# ---------------------------------------------------------------- versions
{
  echo "date: $(date '+%Y-%m-%d %H:%M:%S %Z')"
  echo "gfortran: $(/usr/bin/gfortran --version | head -1)"
  command -v futhark >/dev/null && echo "futhark: $(futhark --version | head -1)"
  echo "gcc (C backend for futhark): $(gcc --version | head -1)"
  echo "kernel: $(uname -srm)"
} > "$EVD/versions.txt"

# ---------------------------------------------------------------- Fortran build + reference tests
make -s -C "$ROOT/fortran/topology" clean > /dev/null 2>&1
if $N make -C "$HERE" driver > "$EVD/fortran_build.log" 2>&1; then
  if grep -qiE '(^|[^-])(warning|error)[: ]' "$EVD/fortran_build.log"; then
    fail fortran_build_clean "compiler diagnostics, see evidence/fortran_build.log"
  else
    pass fortran_build_clean
  fi
else
  fail fortran_build "see evidence/fortran_build.log"
  echo "SUMMARY fail=$NFAIL"; exit 1
fi
rm -f "$FIXD"/*.in "$FIXD"/*.out "$GEOD"/*.lrdrec
$N "$HERE/build/test_topology" "$EVD" "$FIXD" "$GEOD" > "$EVD/fortran_test.log" 2>&1
FRC=$?
grep -E '^(PASS|FAIL) ' "$EVD/fortran_test.log"
NFAIL=$((NFAIL + $(grep -c '^FAIL ' "$EVD/fortran_test.log")))
if [ $FRC -eq 0 ] && grep -q '^FORTRAN SUMMARY pass=[0-9]* fail=0$' "$EVD/fortran_test.log"; then
  pass fortran_driver_exit_status_0
else
  fail fortran_driver_exit_status "exit $FRC (crash or failure), see evidence/fortran_test.log"
fi

# ---------------------------------------------------------------- independent hash cross-checks (coreutils)
S="$EVD/torus_7v_gf2.lrdrec"
if [ -f "$S" ]; then
  A="$(cut -c1-64 "$EVD/torus_7v_gf2.fortran_sha256")"; B="$(sha256sum "$S" | cut -c1-64)"
  [ "$A" = "$B" ] && pass sha256_fortran_equals_coreutils_on_serialization || fail sha256_fortran_equals_coreutils_on_serialization "$A vs $B"
  L="$(grep -an '^LRD-REC-v1$' "$S" | tail -1 | cut -d: -f1)"
  R1="$( { printf 'LRD-COMMIT-v1\0'; tail -n +"$L" "$S"; } | sha256sum | cut -c1-64)"
  R0="$(cut -c1-64 "$EVD/torus_7v_gf2.root")"
  {
    echo "sha256sum of torus_7v_gf2.lrdrec: $B ; Fortran sha256: $A"
    echo "root commitment = sha256('LRD-COMMIT-v1\\0' || last record) via coreutils: $R1 ; Fortran: $R0"
  } > "$EVD/coreutils_crosscheck.txt"
  [ "$R1" = "$R0" ] && pass commitment_root_recomputed_with_coreutils || fail commitment_root_recomputed_with_coreutils "$R1 vs $R0"
else
  fail serialization_written "missing $S"
fi

# ---------------------------------------------------------------- Futhark
if ! command -v futhark >/dev/null 2>&1; then
  unav futhark_inline "futhark not on PATH"
  unav futhark_fixtures_c "futhark not on PATH"
  unav futhark_fixtures_multicore "futhark not on PATH"
else
  GEN="$FIXD/topology_fixtures_test.fut"
  {
    echo "-- Copyright (C) 2026 Bel Esprit D'Accord Irrevocable Trust / SnapKitty Collective Limited"
    echo "-- SPDX-License-Identifier: AGPL-3.0-only AND LicenseRef-SnapKitty-Opaque"
    echo "-- Licensed under AGPL-3.0-only plus the SnapKitty Opaque License (dual license, intentional)."
    echo "-- GENERATED by tests/topology/run.sh from fixtures/manifest.txt (SYNTHETIC fixtures)."
    echo "-- Expected outputs are the Fortran reference values."
    echo "import \"../topology\""
    for E in boundary rank_gfp ddcheck; do
      echo ""
      echo "-- =="
      echo "-- entry: ${E}_fx"
      while read -r STEM ENTRY KIND; do
        [ "$ENTRY" = "$E" ] || continue
        case "$ENTRY" in
          boundary) echo "-- input @ ${STEM}.bnd.in output @ ${STEM}.bnd.out" ;;
          rank_gfp) echo "-- input @ ${STEM}.${KIND}.in output @ ${STEM}.${KIND}.out" ;;
          ddcheck)  echo "-- input @ ${STEM}.dd.in output @ ${STEM}.dd.out" ;;
        esac
      done < "$FIXD/manifest.txt"
      case "$E" in
        boundary) echo 'entry boundary_fx [m][k][n][k1] (fv: [m][k]i64) (fo: [m]i32) (sv: [n][k1]i64) (so: [n]i32) = boundary fv fo sv so' ;;
        rank_gfp) echo 'entry rank_gfp_fx [m][k][n][k1] (p: i64) (fv: [m][k]i64) (fo: [m]i32) (sv: [n][k1]i64) (so: [n]i32) = rank_gfp p fv fo sv so' ;;
        ddcheck)  echo 'entry ddcheck_fx [a][k0][m][k][n][k1] (v0: [a][k0]i64) (o0: [a]i32) (v1: [m][k]i64) (o1: [m]i32) (v2: [n][k1]i64) (o2: [n]i32) = ddcheck v0 o0 v1 o1 v2 o2' ;;
      esac
    done
  } > "$GEN"
  NDS="$(grep -c '^-- input @' "$GEN")"
  ( cd "$FUTD" && $N futhark test --backend=c topology.fut ) > "$EVD/futhark_test_inline_c.log" 2>&1 \
    && pass futhark_inline_c || fail futhark_inline_c "see evidence/futhark_test_inline_c.log"
  for BK in c multicore; do
    ( cd "$FIXD" && $N futhark test --backend=$BK topology_fixtures_test.fut ) > "$EVD/futhark_test_fixtures_$BK.log" 2>&1 \
      && pass "futhark_test_fixtures_${BK}_${NDS}_datasets" || fail "futhark_test_fixtures_${BK}" "see evidence/futhark_test_fixtures_$BK.log"
  done
  # negative control: datacmp must report a single flipped boundary sign as unequal
  NC_IN="$FIXD/SYNTHETIC_filled_triangle_d1.bnd.out"; NC_BAD="$HERE/build/negctl.out"
  sed '1s/-1i32/1i32/' "$NC_IN" > "$NC_BAD"
  if ! futhark datacmp "$NC_IN" "$NC_BAD" > "$EVD/futhark_datacmp_negative_control.txt" 2>&1; then
    pass futhark_datacmp_negative_control_detects_sign_flip
  else
    fail futhark_datacmp_negative_control_detects_sign_flip "datacmp accepted a corrupted matrix"
  fi
  # explicit per-fixture comparison table with compiled executables
  for BK in c multicore; do
    if ( cd "$FIXD" && $N futhark $BK -o "$HERE/build/topology_fx_$BK" topology_fixtures_test.fut ) > "$EVD/futhark_compile_$BK.log" 2>&1; then
      OK=0; BAD=0
      T="$EVD/futhark_vs_fortran_$BK.txt"
      : > "$EVD/futhark_run_$BK.err"
      echo "# stem entry field | Fortran reference | Futhark ($BK executable) | futhark datacmp equal" > "$T"
      while read -r STEM ENTRY KIND; do
        case "$ENTRY" in
          boundary) IN="$FIXD/$STEM.bnd.in"; EXP="$FIXD/$STEM.bnd.out" ;;
          rank_gfp) IN="$FIXD/$STEM.$KIND.in"; EXP="$FIXD/$STEM.$KIND.out" ;;
          ddcheck)  IN="$FIXD/$STEM.dd.in"; EXP="$FIXD/$STEM.dd.out" ;;
        esac
        GOT="$HERE/build/fx_got.out"
        $N "$HERE/build/topology_fx_$BK" -e "${ENTRY}_fx" < "$IN" > "$GOT" 2>>"$EVD/futhark_run_$BK.err"
        XRC=$?
        [ $XRC -eq 0 ] || echo "$STEM $ENTRY exit status $XRC" >> "$EVD/futhark_run_$BK.err"
        if [ $XRC -eq 0 ] && futhark datacmp "$EXP" "$GOT" > /dev/null 2>&1; then M=yes; OK=$((OK+1)); else M=NO; BAD=$((BAD+1)); fi
        if [ "$ENTRY" = boundary ]; then
          echo "$STEM boundary - | $(grep -o 'i32' "$EXP" | wc -l) entries, $(grep -o '\-1i32' "$EXP" | wc -l) of -1, $(grep -oE '(^|[^-0-9])1i32' "$EXP" | wc -l) of +1 | $(grep -o 'i32' "$GOT" | wc -l) entries, $(grep -o '\-1i32' "$GOT" | wc -l) of -1, $(grep -oE '(^|[^-0-9])1i32' "$GOT" | wc -l) of +1 | $M" >> "$T"
        else
          echo "$STEM $ENTRY ${KIND:--} | $(tr '\n' ' ' < "$EXP")| $(tr '\n' ' ' < "$GOT")| $M" >> "$T"
        fi
      done < "$FIXD/manifest.txt"
      echo "# total equal=$OK unequal=$BAD" >> "$T"
      [ $BAD -eq 0 ] && pass "futhark_${BK}_executable_matches_fortran_${OK}_of_$((OK+BAD))" \
                     || fail "futhark_${BK}_executable_matches_fortran" "$BAD mismatches, see evidence/futhark_vs_fortran_$BK.txt"
    else
      fail "futhark_compile_$BK" "see evidence/futhark_compile_$BK.log"
    fi
  done
fi

# ---------------------------------------------------------------- Self
SELFBIN=""; SELFOBJ=""
for CAND in "$TOOLS/self-src/build32/vm/Self" /workspace/_causal_tools/self-src/build32/vm/Self; do
  if [ -x "$CAND" ]; then SELFBIN="$CAND"; SELFOBJ="$(cd "$(dirname "$CAND")/../../objects" && pwd)"; break; fi
done
if [ -z "$SELFBIN" ]; then
  unav self_headless "no built Self VM under $TOOLS or /workspace/_causal_tools"
  unav self_gui "no built Self VM"
else
  echo "self: $SELFBIN (objects $SELFOBJ); source commit $(git -C "$SELFOBJ/.." log -1 --format='%h %ad' --date=short 2>/dev/null)" >> "$EVD/versions.txt"
  ( cd "$SELFOBJ" && TOPO_SELF_DIR="$SELFD" TOPO_GEOM_DIR="$GEOD" timeout 300 $N "$SELFBIN" -f worldBuilder.self -b . -o none \
      -f2 "$HERE/self_headless.self" < /dev/null ) > "$EVD/self_headless_full.log" 2>&1
  SRC=$?
  if [ $SRC -eq 0 ]; then pass self_headless_exit_status_0; else fail self_headless_exit_status "exit $SRC (crash or timeout), see evidence/self_headless_full.log"; fi
  grep -E '^(PASS|FAIL|SELF) ' "$EVD/self_headless_full.log" > "$EVD/self_headless.log"
  grep -E '^(PASS|FAIL) ' "$EVD/self_headless.log"
  NFAIL=$((NFAIL + $(grep -c '^FAIL ' "$EVD/self_headless.log")))
  grep -q SELF_HEADLESS_DONE "$EVD/self_headless_full.log" && pass self_headless_completed || fail self_headless_completed "see evidence/self_headless_full.log"
  # Self-read commitment roots must equal the Fortran GF(2) roots
  RB=0; RN=0
  while read -r NAME FIELD ROOT; do
    RN=$((RN+1))
    SR="$(grep "^SELF $NAME " "$EVD/self_headless.log" | sed 's/.* root=//')"
    [ "$SR" = "$ROOT" ] || RB=$((RB+1))
  done < <(grep '^SYNTHETIC_.* GF(2) ' "$EVD/commitments.txt" | awk 'NF==3')
  if [ $RB -eq 0 ] && [ $RN -gt 0 ]; then pass "self_roots_equal_fortran_${RN}_fixtures"; else fail self_roots_equal_fortran "$RB of $RN differ"; fi
  # GUI under Xvfb
  if command -v Xvfb >/dev/null && command -v import >/dev/null; then
    # pick a display number with no X socket or lock file (other agents run Xvfb on this box)
    DNUM=""
    for D in $(seq 140 199); do
      if [ ! -e "/tmp/.X11-unix/X$D" ] && [ ! -e "/tmp/.X$D-lock" ]; then DNUM=":$D"; break; fi
    done
    XPID=""
    if [ -n "$DNUM" ]; then
      Xvfb "$DNUM" -screen 0 1440x900x24 -nolisten tcp > "$EVD/xvfb.log" 2>&1 &
      XPID=$!
    fi
    sleep 2
    if [ -z "$DNUM" ] || ! kill -0 "$XPID" 2>/dev/null; then
      fail self_gui_xvfb_start "could not start a private Xvfb, see evidence/xvfb.log"
    else
    FIFO="$HERE/build/self_gui.fifo"; rm -f "$FIFO"; mkfifo "$FIFO"
    ( cd "$SELFOBJ" && DISPLAY="$DNUM" TOPO_SELF_DIR="$SELFD" TOPO_GEOM_DIR="$GEOD" exec timeout 400 $N "$SELFBIN" -f worldBuilder.self -b . \
        -o morphic -f2 "$SELFD/gui_demo.self" < "$FIFO" ) > "$EVD/self_gui_full.log" 2>&1 &
    SPID=$!   # the subshell execs timeout, so this is timeout's PID; timeout forwards TERM to Self
    exec 7>"$FIFO"
    for _ in $(seq 1 100); do sleep 3; grep -q "Scheduler started" "$EVD/self_gui_full.log" && break; done
    sleep 3; echo "topologyGuiDemo run" >&7
    for _ in $(seq 1 40); do sleep 2; grep -q "GUI_DEMO_DONE" "$EVD/self_gui_full.log" && break; done
    sleep 8
    rm -f "$EVD/self_morphic_topology.png"
    if kill -0 "$SPID" 2>/dev/null; then GUIALIVE=1; else GUIALIVE=0; wait "$SPID"; GUIRC=$?; fi
    DISPLAY="$DNUM" import -window root "$EVD/self_morphic_topology.png" > /dev/null 2>&1
    IMRC=$?
    exec 7>&-
    kill "$SPID" > /dev/null 2>&1; wait "$SPID" 2>/dev/null
    kill $XPID > /dev/null 2>&1; rm -f "$FIFO"
    grep -E '^GUI' "$EVD/self_gui_full.log" > "$EVD/self_gui.log"
    if [ $GUIALIVE -ne 1 ]; then
      fail self_gui_process_alive "Self GUI process exited early with status ${GUIRC:-?}, see evidence/self_gui_full.log"
    else
      pass self_gui_process_alive_until_screenshot
    fi
    if [ $IMRC -eq 0 ] && grep -q GUI_DEMO_DONE "$EVD/self_gui_full.log" && [ -s "$EVD/self_morphic_topology.png" ]; then
      pass self_gui_morphic_screenshot
    else
      fail self_gui_morphic_screenshot "see evidence/self_gui_full.log"
    fi
    fi
  else
    unav self_gui "Xvfb or ImageMagick import not installed"
  fi
fi

echo "SUMMARY fail=$NFAIL"
[ $NFAIL -eq 0 ]
