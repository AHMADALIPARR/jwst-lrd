# Detects the toolchain and writes build/TOOLCHAIN.lock.
# With LRD_INSTALL=1, installs missing free tools first (apt; PAKCS + Self via
# build/install-curry-self.sh). Logs go to build/logs/.
# Lock format: one record per tool, key=value lines, blank line between tools:
#   tool=<name>  version=<string as reported by the tool>  path=<abs path>
#   sha256=<sha256 of that file>  status=OK|UNAVAILABLE  [reason=...]  [note=...]
set -u
ROOT=$(cd "$(dirname "$0")/.." && pwd)
LOGS=$ROOT/build/logs; mkdir -p "$LOGS"
LOCK=$ROOT/build/TOOLCHAIN.lock
# Tool search dirs for source/tarball installs: this checkout, then the shared main checkout.
TOOLDIRS="$ROOT/build/tools ${LRD_SHARED_TOOLS:-/workspace/jwst-lrd/build/tools}"

APT_PKGS="gfortran gcc clang llvm libcfitsio-dev libgmp-dev libssl-dev libcurl4-openssl-dev curl jq agda agda-stdlib futhark octave"
if [ "${LRD_INSTALL:-0}" = "1" ]; then
  missing=""
  for p in $APT_PKGS; do dpkg -s "$p" >/dev/null 2>&1 || missing="$missing $p"; done
  if [ -n "$missing" ]; then
    echo "toolchain: apt-get install$missing (log build/logs/toolchain-apt.log)"
    sudo DEBIAN_FRONTEND=noninteractive apt-get install -y $missing > "$LOGS/toolchain-apt.log" 2>&1 \
      || echo "toolchain: apt-get failed, see log"
  fi
  found_pakcs=""; found_self=""
  for d in $TOOLDIRS; do
    [ -x "$d/pakcs-3.10.0/bin/pakcs" ] && found_pakcs=1
    [ -x "$d/self-src/build32/vm/Self" ] && found_self=1
  done
  if [ -z "$found_pakcs" ] || [ -z "$found_self" ]; then
    sh "$ROOT/build/install-curry-self.sh" > "$LOGS/install-curry-self.log" 2>&1 \
      || echo "toolchain: install-curry-self failed, see build/logs/install-curry-self.log"
  fi
fi

sha() { sha256sum "$1" | cut -d' ' -f1; }
first_in_tooldirs() { for d in $TOOLDIRS; do [ -e "$d/$1" ] && { echo "$d/$1"; return 0; }; done; return 1; }
emit_ok() { # name version path [note]
  real=$(readlink -f "$3")
  { echo "tool=$1"; echo "status=OK"; echo "version=$2"; echo "path=$real"; echo "sha256=$(sha "$real")"
    [ -n "${4:-}" ] && echo "note=$4"; echo; } >> "$LOCK.tmp"
  printf '%-14s OK           %s\n' "$1" "$2"
}
emit_unav() { # name reason
  { echo "tool=$1"; echo "status=UNAVAILABLE"; echo "reason=$2"; echo; } >> "$LOCK.tmp"
  printf '%-14s UNAVAILABLE  %s\n' "$1" "$2"
}
bin_tool() { # name cmd version-command (evaluated)
  p=$(command -v "$2" 2>/dev/null) || { emit_unav "$1" "$2 not found on PATH"; return; }
  v=$(eval "$3" 2>&1 | head -1)
  emit_ok "$1" "$v" "$p" "${4:-}"
}
lib_tool() { # name pkgconfig-name dpkg-name soname
  v=$(pkg-config --modversion "$2" 2>/dev/null) || { emit_unav "$1" "pkg-config $2 not found"; return; }
  d=$(dpkg-query -W -f='${Version}' "$3" 2>/dev/null)
  so=$(pkg-config --variable=libdir "$2")/$4
  [ -e "$so" ] || { emit_unav "$1" "library $so missing"; return; }
  emit_ok "$1" "$v (pkg-config $2; dpkg $3 $d)" "$so"
}

: > "$LOCK.tmp"
{ echo "# TOOLCHAIN.lock (generated by build/toolchain.sh; do not edit by hand)"
  echo "# host=$(uname -srm)"
  echo "# generated=$(date -u +%Y-%m-%dT%H:%M:%SZ)"; echo; } >> "$LOCK.tmp"
bin_tool gfortran gfortran 'gfortran --version'
bin_tool gcc gcc 'gcc --version'
bin_tool clang clang 'clang --version'
bin_tool llvm llvm-config 'echo "LLVM $(llvm-config --version)"'
bin_tool llvm-opt opt 'opt --version | grep -i version'
lib_tool libcfitsio-dev cfitsio libcfitsio-dev libcfitsio.so
lib_tool libgmp-dev gmp libgmp-dev libgmp.so
lib_tool libssl-dev openssl libssl-dev libssl.so
lib_tool libcurl-dev libcurl libcurl4-openssl-dev libcurl.so
bin_tool curl curl 'curl --version'
bin_tool jq jq 'jq --version'
bin_tool agda agda 'agda --version'
if [ -f /usr/share/agda-stdlib/standard-library.agda-lib ]; then
  emit_ok agda-stdlib "$(grep -m1 '^name:' /usr/share/agda-stdlib/standard-library.agda-lib) (dpkg agda-stdlib $(dpkg-query -W -f='${Version}' agda-stdlib))" \
    /usr/share/agda-stdlib/standard-library.agda-lib "path is the .agda-lib file"
else emit_unav agda-stdlib "standard-library.agda-lib not found"; fi
bin_tool futhark futhark 'futhark --version'
bin_tool swi-prolog swipl 'swipl --version' "backend for PAKCS"
if pk=$(first_in_tooldirs pakcs-3.10.0/bin/pakcs); then
  v=$("$pk" --version 2>&1 | grep -m1 'Version')
  # bin/pakcs is a shell wrapper; hash the saved SWI-Prolog state it executes as well.
  st=$(dirname "$pk")/../src/pakcs
  emit_ok curry-pakcs "PAKCS $(echo "$v" | sed "s/.*Version/Version/")" "$pk" "Curry system PAKCS; wrapper script, runtime state $(readlink -f "$st") sha256=$( [ -f "$st" ] && sha "$st" || echo n/a)"
else emit_unav curry-pakcs "PAKCS not installed (run LRD_INSTALL=1 make toolchain)"; fi
if sv=$(first_in_tooldirs self-src/build32/vm/Self); then
  v=$(echo | "$sv" 2>&1 | grep -m1 'Self Virtual Machine Version')
  emit_ok self-vm "$v" "$sv" "built from github.com/russellallen/self ($(git -C "$(dirname "$sv")/../.." describe --tags 2>/dev/null)); bare VM, no world snapshot"
else emit_unav self-vm "Self VM not built (run LRD_INSTALL=1 make toolchain)"; fi
if p=$(command -v octave 2>/dev/null); then
  v=$(octave --version 2>&1 | head -1)
  emit_ok octave "$v" "$p" "GNU Octave (runs .m files; NOT MATLAB)"
else emit_unav octave "GNU Octave (runs .m files; NOT MATLAB) not installed"; fi
if command -v matlab >/dev/null 2>&1; then emit_ok matlab "$(matlab -batch 'disp(version)' 2>&1 | tail -1)" "$(command -v matlab)"
else emit_unav matlab "licensed (MathWorks MATLAB is proprietary; not installed)"; fi
if command -v sas >/dev/null 2>&1; then emit_ok sas "present" "$(command -v sas)"
else emit_unav sas "licensed (SAS Institute software is proprietary; not installed)"; fi
mv "$LOCK.tmp" "$LOCK"
echo "toolchain: wrote $LOCK"
